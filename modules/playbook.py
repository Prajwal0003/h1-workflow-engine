"""
Playbook module — Generates manual hunting guides based on technology stack.
"""

from pathlib import Path
from . import config
from .config import console

def generate_playbook(handle, tech_stack=None):
    """Generates a Markdown playbook for manual testing."""
    if tech_stack is None:
        tech_stack = []
        
    out_file = config.RECON_DIR / f"{handle}_hunting_playbook.md"
    
    content = f"# Manual Hunting Playbook: {handle}\n\n"
    content += "This guide provides specialized manual testing strategies based on the target's identified technologies.\n\n"
    
    # Generic web testing
    content += "## 1. General Business Logic & Access Control\n"
    content += "- **IDOR (Insecure Direct Object Reference):** Test if User A can access User B's data by manipulating IDs in URLs or JSON bodies.\n"
    content += "- **Privilege Escalation:** Attempt to access administrative endpoints (`/admin`, `/dashboard`) using a low-privilege token.\n"
    content += "- **Race Conditions:** Send simultaneous requests to endpoints dealing with limits, balances, or one-time actions.\n\n"
    
    # Tech specific strategies
    tech_str = " ".join(t.lower() for t in tech_stack)
    
    if "next.js" in tech_str or "react" in tech_str:
        content += "## 2. Next.js / React Specifics\n"
        content += "- **Hidden Routes:** Check `_next/data/` for data leaks from server-side props.\n"
        content += "- **Source Maps:** Look for `*.js.map` files to read the uncompiled source code.\n"
        content += "- **XSS:** Look for `dangerouslySetInnerHTML` usage or improper handling of user input passed to props.\n\n"
        
    if "kong" in tech_str or "api" in tech_str or "graphql" in tech_str:
        content += "## 3. API & API Gateway (Kong/GraphQL)\n"
        content += "- **GraphQL Introspection:** Try sending `{ __schema { types { name } } }` to discover all endpoints.\n"
        content += "- **Mass Assignment:** When updating a profile, try adding fields like `\"is_admin\": true` or `\"role\": \"admin\"`.\n"
        content += "- **API Versioning:** If `/v2/` is secure, try the same request against `/v1/`.\n\n"
        
    if "php" in tech_str:
        content += "## 4. PHP Specifics\n"
        content += "- **Type Juggling:** Test authentication bypasses using loose comparisons (e.g., passing arrays instead of strings).\n"
        content += "- **LFI (Local File Inclusion):** Check `?page=` or `?file=` parameters for path traversal (`../../../../etc/passwd`).\n\n"
        
    # Fuzzing reminder
    content += "## 5. Fuzzing Follow-up\n"
    content += "- Check the `_fuzz_findings.json` report generated by the recon pipeline.\n"
    content += "- Manually verify any flagged endpoints in Burp Suite using Repeater.\n\n"
    
    out_file.write_text(content)
    console.print(f"[green]✓ Generated custom hunting playbook: {out_file}[/green]")
    return out_file
