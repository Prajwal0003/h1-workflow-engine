"""HackerOne API Reporter — Auto-submit verified findings"""
import requests
import json
from typing import Dict, Optional

class H1Reporter:
    def __init__(self, h1_api_token: str, h1_username: str):
        self.h1_api_token = h1_api_token
        self.h1_username = h1_username
        self.base_url = "https://api.hackerone.com/v1"
        self.headers = {
            "Authorization": f"Bearer {h1_api_token}",
            "Content-Type": "application/json",
            "Accept": "application/json"
        }
    
    def submit_report(self, program_handle: str, finding: Dict) -> Optional[str]:
        """Submit verified finding to HackerOne"""
        if not finding.get("verified"):
            print(f"[-] Finding not verified, skipping")
            return None
        
        title = f"[{finding.get('severity')}] {finding.get('type')}"
        description = f"""Type: {finding.get('type')}
Severity: {finding.get('severity')}
URL: {finding.get('url')}
Detail: {finding.get('detail', 'N/A')}

PoC Output:
{finding.get('poc_output', 'N/A')}

Auto-generated by AI Brain"""
        
        payload = {
            "data": {
                "type": "report",
                "attributes": {
                    "title": title,
                    "description": description,
                    "severity_rating": finding.get('severity', 'high').lower()
                },
                "relationships": {
                    "program": {
                        "data": {"type": "program", "id": program_handle}
                    }
                }
            }
        }
        
        try:
            url = f"{self.base_url}/reports"
            r = requests.post(url, json=payload, headers=self.headers, timeout=30)
            if r.status_code in [201, 200]:
                report_id = r.json().get('data', {}).get('id')
                print(f"[+] Submitted to H1! ID: {report_id}")
                return report_id
        except Exception as e:
            print(f"[-] H1 error: {e}")
        
        return None
